// A small deterministic alpha grain, embedded for offline WXSS backgrounds.
// Regenerate with node scripts/card-paper-texture.js (no runtime canvas work).
const fs = require('node:fs');
const path = require('node:path');
const { createCanvas } = require('@napi-rs/canvas');
const canvas = createCanvas(128, 128), ctx = canvas.getContext('2d');
const pixels = ctx.createImageData(128, 128); let seed = 2817;
for (let i = 0; i < pixels.data.length; i += 4) {
  seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
  const n = seed >>> 24;
  pixels.data[i] = pixels.data[i + 1] = pixels.data[i + 2] = n;
  pixels.data[i + 3] = Math.round(Math.abs(n - 128) * .7);
}
ctx.putImageData(pixels, 0, 0);
const data = canvas.toBuffer('image/png').toString('base64');
fs.writeFileSync(path.resolve(__dirname, '../miniprogram/styles/card-paper.wxss'),
  '/* Generated by scripts/card-paper-texture.js. */\n.card-paper-grain { background-image:url("data:image/png;base64,' + data + '"); background-repeat:repeat; background-size:128px 128px; }\n');
